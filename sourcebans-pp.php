#!/usr/bin/php
<?php

// sourcebans-pp: sets up and upgrades the database of the packaged SourceBans++ panel from the
// command line, in place of the install wizard and the web updater, which the panel refuses to run
// next to. The steps of upstream's production Docker image (docker/php/prod-entrypoint.sh): the
// configuration, the schema with the first admin, and the updater's migrations.

declare(strict_types=1);

// The panel, the wizard's schema and the updater (outside the web root) and the configuration;
// the environment can point at others, e.g. for a test
const PANEL_ROOT = '/usr/share/webapps/sourcebans-pp';
const SETUP_DIR = '/usr/share/sourcebans-pp';
const CONFIG_PATH = '/etc/webapps/sourcebans-pp/config.php';

// The settings, the names of upstream's Docker image, with its defaults
const SETTINGS = [
    'DB_HOST' => ['Database host', 'localhost'],
    'DB_PORT' => ['Database port', '3306'],
    'DB_NAME' => ['Database name', 'sourcebans'],
    'DB_USER' => ['Database user', 'sourcebans'],
    'DB_PASS' => ['Database password', null],
    'DB_PREFIX' => ['Table prefix', 'sb'],
    'DB_CHARSET' => ['Character set', 'utf8mb4'],
    'STEAMAPIKEY' => ['Steam Web API key (optional)', ''],
    'SB_EMAIL' => ['Sender address of the panel\'s mails (optional)', ''],
];
const ADMIN_SETTINGS = [
    'INITIAL_ADMIN_NAME' => ['First admin\'s name', null],
    'INITIAL_ADMIN_STEAM' => ['First admin\'s Steam ID (STEAM_0:X:NNNNNNN)', null],
    'INITIAL_ADMIN_EMAIL' => ['First admin\'s email address', null],
    'INITIAL_ADMIN_PASSWORD' => ['First admin\'s password (8 characters or more)', null],
];
const SECRETS = ['DB_PASS', 'INITIAL_ADMIN_PASSWORD'];

function fail(string $message): never
{
    fwrite(STDERR, "sourcebans-pp: $message\n");
    exit(1);
}

function info(string $message): void
{
    fwrite(STDERR, ":: $message\n");
}

function path(string $variable, string $default): string
{
    $value = getenv($variable);
    return is_string($value) && $value !== '' ? $value : $default;
}

// A setting from the environment, else asked for on a terminal (secrets without echo), else its
// default
function setting(string $name, string $prompt, ?string $default): string
{
    $value = getenv($name);
    if (is_string($value) && $value !== '') {
        return $value;
    }
    if (!stream_isatty(STDIN)) {
        if ($default === null) {
            fail("$name is not set (the environment sets it when there's no terminal to ask on)");
        }
        return $default;
    }
    $secret = in_array($name, SECRETS, true);
    fwrite(STDERR, $prompt . ($default !== null && $default !== '' ? " [$default]" : '') . ': ');
    if ($secret) {
        shell_exec('stty -echo');
    }
    $line = fgets(STDIN);
    if ($secret) {
        shell_exec('stty echo');
        fwrite(STDERR, "\n");
    }
    $value = rtrim($line === false ? '' : $line, "\r\n");
    if ($value === '') {
        if ($default === null) {
            fail("$name is required");
        }
        return $default;
    }
    return $value;
}

function settings(array $definitions): array
{
    $values = [];
    foreach ($definitions as $name => [$prompt, $default]) {
        $values[$name] = setting($name, $prompt, $default);
    }
    return $values;
}

// The configuration like the install wizard's (web/install/pages/page.5.php), with a new JWT
// signing key
function render_config(array $s): string
{
    $esc = static fn(string $v): string => str_replace(['\\', "'"], ['\\\\', "\\'"], $v);
    $lines = ["<?php", "// Generated by sourcebans-pp setup."];
    foreach (['DB_HOST', 'DB_USER', 'DB_PASS', 'DB_NAME', 'DB_PREFIX', 'DB_PORT', 'DB_CHARSET', 'STEAMAPIKEY', 'SB_EMAIL'] as $name) {
        $lines[] = "define('$name', '" . $esc($s[$name]) . "');";
    }
    $lines[] = "define('SB_NEW_SALT', '\$5\$');";
    $lines[] = "define('SB_SECRET_KEY', '" . base64_encode(random_bytes(47)) . "');";
    return implode("\n", $lines) . "\n";
}

// The configuration's settings, as the panel loads them
function load_config(string $configPath): void
{
    if (!defined('IN_SB')) {
        define('IN_SB', true);
    }
    require_once $configPath;
    if (!defined('DB_CHARSET')) {
        define('DB_CHARSET', 'utf8mb4');
    }
}

function open_database(string $panelRoot): \Database
{
    require_once $panelRoot . '/includes/vendor/autoload.php';
    require_once $panelRoot . '/includes/Db/Database.php';
    // The Database class dies on a failed connection: try it with PDO first for an error message
    $dsn = sprintf('mysql:host=%s;port=%d;dbname=%s;charset=%s', DB_HOST, (int) DB_PORT, DB_NAME, DB_CHARSET);
    try {
        new \PDO($dsn, DB_USER, DB_PASS, [\PDO::ATTR_ERRMODE => \PDO::ERRMODE_EXCEPTION, \PDO::ATTR_TIMEOUT => 5]);
    } catch (\PDOException $e) {
        fail('could not connect to the database: ' . $e->getMessage());
    }
    return new \Database(DB_HOST, (int) DB_PORT, DB_NAME, DB_USER, DB_PASS, DB_PREFIX, DB_CHARSET);
}

// Whether the panel's tables exist: the settings' config.version row, like the Docker image checks
function installed(\Database $db): bool
{
    try {
        $db->query("SELECT value FROM `:prefix_settings` WHERE setting = 'config.version'");
        return $db->single() !== false;
    } catch (\PDOException) {
        return false;
    }
}

// The statements of one of the wizard's SQL files, with its placeholders replaced, run like the
// wizard does
function run_sql_file(\Database $db, string $file): void
{
    $sql = file_get_contents($file);
    if ($sql === false) {
        fail("can't read $file");
    }
    $sql = str_replace(['{prefix}', '{charset}'], [DB_PREFIX, DB_CHARSET], $sql);
    foreach (explode(';', $sql) as $statement) {
        $statement = trim($statement);
        if (strlen($statement) <= 2) {
            continue;
        }
        $db->query($statement);
        $db->execute();
    }
}

// The schema, the first admin (an owner, like the wizard creates) and the default settings, in the
// wizard's order
function install(\Database $db, string $setupDir): void
{
    $admin = settings(ADMIN_SETTINGS);
    $steam = $admin['INITIAL_ADMIN_STEAM'];
    if (preg_match('/^STEAM_[01]:[01]:[0-9]+$/D', $steam) !== 1) {
        fail('the Steam ID must be in the STEAM_0:X:NNNNNNN format');
    }
    if (filter_var($admin['INITIAL_ADMIN_EMAIL'], FILTER_VALIDATE_EMAIL) === false) {
        fail('the email address is invalid');
    }
    if (strlen($admin['INITIAL_ADMIN_PASSWORD']) < 8) {
        fail('the password must have 8 characters or more');
    }

    info('Creating the tables');
    run_sql_file($db, $setupDir . '/install/includes/sql/struc.sql');
    info("Adding the admin {$admin['INITIAL_ADMIN_NAME']}");
    $db->query(
        'INSERT INTO `:prefix_admins` (user, authid, password, gid, email, extraflags, immunity) '
        . 'VALUES (:user, :authid, :password, :gid, :email, :extraflags, :immunity)'
    );
    $db->bind(':user', $admin['INITIAL_ADMIN_NAME']);
    $db->bind(':authid', str_replace('STEAM_1', 'STEAM_0', $steam));
    $db->bind(':password', password_hash($admin['INITIAL_ADMIN_PASSWORD'], PASSWORD_BCRYPT));
    $db->bind(':gid', -1);
    $db->bind(':email', $admin['INITIAL_ADMIN_EMAIL']);
    $db->bind(':extraflags', 1 << 24);
    $db->bind(':immunity', 100);
    $db->execute();
    info('Adding the default settings');
    run_sql_file($db, $setupDir . '/install/includes/sql/data.sql');
}

// The updater's migrations up to this version, like upstream's headless updater driver in the
// Docker image
function migrate(\Database $db, string $panelRoot, string $setupDir): void
{
    define('IS_UPDATE', true);
    define('ROOT', $panelRoot . '/');
    define('SB_THEMES', $panelRoot . '/themes/');
    define('SB_CACHE', $panelRoot . '/cache/');
    define('INCLUDES_PATH', $panelRoot . '/includes');
    // The updater reads store.json and data/<version>.php relative to its directory
    chdir($setupDir . '/updater');
    require_once $setupDir . '/updater/Updater.php';
    $updater = new \Updater($db);
    $failed = false;
    foreach ($updater->getMessageStack() as $line) {
        $text = strip_tags((string) $line);
        // The updater's messages; "Please delete the /updater folder." doesn't apply here
        if (!str_starts_with($text, 'Updated successfully.')) {
            info($text);
        }
        if (str_contains($text, 'Error executing:') || str_contains($text, 'Update Failed!')) {
            $failed = true;
        }
    }
    if ($failed) {
        fail('a migration failed, the database is partially upgraded');
    }
}

// The entry of SourceMod's databases.cfg the plugins connect with, like the wizard shows it
function databases_cfg(): string
{
    $kv = static fn(string $v): string => str_replace(['\\', '"'], ['\\\\', '\\"'], $v);
    return "\t\"sourcebans\"\n\t{\n"
        . "\t\t\"driver\"   \"default\"\n"
        . "\t\t\"host\"     \"" . $kv(DB_HOST) . "\"\n"
        . "\t\t\"database\" \"" . $kv(DB_NAME) . "\"\n"
        . "\t\t\"user\"     \"" . $kv(DB_USER) . "\"\n"
        . "\t\t\"pass\"     \"" . $kv(DB_PASS) . "\"\n"
        . "\t\t\"port\"     \"" . (int) DB_PORT . "\"\n"
        . "\t}\n";
}

function usage(): never
{
    fwrite(STDERR, <<<'TEXT'
        Usage: sourcebans-pp <command>

          setup          Write the configuration if there's none, create the database's tables and the
                         first admin if they don't exist, and run pending migrations
          upgrade        Run the migrations of a new version (after upgrading the package)
          databases-cfg  Print the "sourcebans" entry of SourceMod's configs/databases.cfg

        setup asks for its settings on a terminal, or takes them from the environment:
          DB_HOST DB_PORT DB_NAME DB_USER DB_PASS DB_PREFIX DB_CHARSET STEAMAPIKEY SB_EMAIL
          INITIAL_ADMIN_NAME INITIAL_ADMIN_STEAM INITIAL_ADMIN_EMAIL INITIAL_ADMIN_PASSWORD
        The database and its user have to exist. The configuration is /etc/webapps/sourcebans-pp/config.php
        (SBPP_CONFIG_PATH, like the panel).

        TEXT);
    exit(2);
}

$command = $argv[1] ?? '';
if (!in_array($command, ['setup', 'upgrade', 'databases-cfg'], true)) {
    usage();
}
if (!extension_loaded('pdo_mysql')) {
    fail('PHP\'s pdo_mysql extension is not enabled (extension=pdo_mysql in /etc/php/php.ini)');
}
$panelRoot = path('SBPP_PANEL_ROOT', PANEL_ROOT);
$setupDir = path('SBPP_SETUP_DIR', SETUP_DIR);
$configPath = path('SBPP_CONFIG_PATH', CONFIG_PATH);

if ($command === 'setup' && !file_exists($configPath)) {
    $s = settings(SETTINGS);
    foreach (['DB_PREFIX', 'DB_CHARSET'] as $name) {
        if (preg_match('/^[A-Za-z0-9_]+$/D', $s[$name]) !== 1) {
            fail("$name may only contain letters, digits and underscores");
        }
    }
    if (strlen($s['DB_PREFIX']) > 9) {
        fail('DB_PREFIX may have 9 characters at most');
    }
    if (preg_match('/^[0-9]+$/D', $s['DB_PORT']) !== 1) {
        fail('DB_PORT must be a number');
    }
    info("Writing $configPath");
    // Readable by the web server's group only (it has the database password and the JWT key)
    $old = umask(0o027);
    $written = file_put_contents($configPath, render_config($s), LOCK_EX);
    umask($old);
    if ($written === false) {
        fail("can't write $configPath");
    }
    if (posix_geteuid() === 0) {
        chgrp($configPath, 'http');
    }
}
if (!is_readable($configPath)) {
    fail("can't read $configPath" . ($command === 'setup' ? '' : ' (run sourcebans-pp setup first)'));
}
load_config($configPath);

if ($command === 'databases-cfg') {
    echo databases_cfg();
    exit(0);
}

$db = open_database($panelRoot);
$fresh = !installed($db);
if ($fresh) {
    if ($command === 'upgrade') {
        fail('the database has no SourceBans++ tables (run sourcebans-pp setup)');
    }
    install($db, $setupDir);
}
migrate($db, $panelRoot, $setupDir);
if ($fresh) {
    info('Done. The entry of SourceMod\'s configs/databases.cfg for the game servers\' plugins:');
    echo databases_cfg();
}
