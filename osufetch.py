def load_or_ask_user():
    if os.path.exists(CONFIG_FILE):
        with open(CONFIG_FILE, 'r') as f:
            config = json.load(f)
            return config.get("username"), config.get("api_key")
    else:
        print(f"{PINK}{BOLD}Добро пожаловать в osu!fetch!{RESET}")
        print(f"{GRAY}Для работы утилиты нужен Legacy API v1 ключ.{RESET}\n")
        username = input(f"{WHITE}Введите ваш ник в osu!: {RESET}").strip()
        api_key = input(f"{WHITE}Введите ваш osu! API Key (инструкция на https://github.com/test2793/osu-fetch): {RESET}").strip()
        with open(CONFIG_FILE, 'w') as f:
            json.dump({"username": username, "api_key": api_key}, f)
        return username, api_key

def get_stats(username, api_key):
    url = f"https://osu.ppy.sh/api/get_user?k={api_key}&u={username}&m=0"
    try:
        res = requests.get(url)
        if res.status_code != 200:
            return [f"{PURPLE}Ошибка API{RESET}: Код {res.status_code}"]

        response = res.json()
        if not response:
            return [f"{PURPLE}Ошибка{RESET}: Пользователь не найден!"]

        data = response[0]
        return [
            f"{PINK}{BOLD}{data['username']}{RESET}@{PINK}osu",
            f"{GRAY}-----------------------------------{RESET}",
            f"{PURPLE}Rank{RESET}:     #{int(data['pp_rank']):,}",
            f"{PURPLE}Country{RESET}:  #{int(data['pp_country_rank']):,} ({data['country']})",
            f"{PURPLE}PP{RESET}:       {float(data['pp_raw']):.2f} pp",
            f"{PURPLE}Accuracy{RESET}: {float(data['accuracy']):.2f}%",
            f"{PURPLE}Level{RESET}:    {float(data['level']):.0f}",
            f"{PURPLE}Playcount{RESET}: {int(data['playcount']):,}",
            f"{GRAY}-----------------------------------{RESET}",
            f"{PINK}Config{RESET}:    {CONFIG_FILE}"
        ]
    except Exception as err:
        return [f"{PURPLE}Ошибка программы{RESET}: {str(err)}"]

def run():
    username, api_key = load_or_ask_user()
    os.system('cls' if os.name == 'nt' else 'clear')
    stats = get_stats(username, api_key)

    art_len = len(ASCII_ART)
    offset = 12

    for i in range(max(art_len, len(stats) + offset)):
        if i < art_len:
            print(f"{PINK}{ASCII_ART[i]}{RESET}", end="  ")
        else:
            print(" " * len(ASCII_ART[0]), end="  ")

        stat_idx = i - offset
        if 0 <= stat_idx < len(stats):
            print(stats[stat_idx])
        else:
            print()

if __name__ == "__main__":
    run()
