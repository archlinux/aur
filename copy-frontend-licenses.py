"""Collect licenses for actual source-map modules and the selected table assets."""
from pathlib import Path
import hashlib
import json
import shutil
import sys

vega, embed, jquery, tables, output, icons = map(lambda p: Path(p).resolve(), sys.argv[1:])
rows = []


def copy_notices(package, label, destination, fallback=None):
    files = sorted(p for p in package.iterdir()
                   if p.is_file() and p.name.lower().startswith(
                       ('license', 'licence', 'copying', 'notice', 'copyright')))
    if not files and fallback is not None:
        files = [fallback]
    assert files, ('Missing license notice', package)
    copied = []
    for source in files:
        name = label.replace('/', '__').replace('@', '') + '-' + source.name
        destination.mkdir(parents=True, exist_ok=True)
        target = destination / name
        if target.exists():
            assert target.read_bytes() == source.read_bytes(), target
        else:
            shutil.copyfile(source, target)
        copied.append({'file': name, 'sha256': hashlib.sha256(target.read_bytes()).hexdigest()})
    return copied


# These maps are generated by the current source builds, never by the original
# vendored minified assets. They include the upstream libraries compiled into JS.
for root, mapfile in [(vega, vega / 'packages/vega/build/vega.js.map'),
                      (embed, embed / 'build/vega-embed.js.map')]:
    data = json.loads(mapfile.read_text())
    assert data['sources']
    packages = {}
    for source in data['sources']:
        path = (mapfile.parent / source).resolve()
        assert path.is_relative_to(root), source
        assert path.is_file(), path
        directory = path.parent
        while directory.is_relative_to(root):
            manifest = directory / 'package.json'
            if manifest.is_file():
                metadata = json.loads(manifest.read_text())
                if metadata.get('name') and metadata.get('version'):
                    packages.setdefault(directory, {'name': metadata['name'],
                        'version': metadata['version'], 'modules': []})['modules'].append(str(path.relative_to(directory)))
                    break
            directory = directory.parent
        else:
            raise AssertionError(('Unidentified bundled source', source))
    for package, row in sorted(packages.items()):
        fallback = vega / 'LICENSE' if package.is_relative_to(vega / 'packages') else None
        if package == embed / 'build':
            # TypeScript copies the imported root package.json into build/.
            metadata = json.loads((embed / 'package.json').read_text())
            assert (row['name'], row['version']) == (metadata['name'], metadata['version'])
            fallback = embed / 'LICENSE'
        row['notices'] = copy_notices(package, row['name'] + '-' + row['version'],
                                     output / 'vega', fallback)
        row['modules'] = sorted(set(row['modules']))
        rows.append(row)

for package, name, version in [(jquery, 'jquery', '3.7.0'),
        (tables, 'datatables', '2.3.8'),
        (tables / 'extensions/FixedHeader', 'fixedheader', '4.0.6'),
        (tables / 'extensions/ColumnControl', 'columncontrol', '1.2.1')]:
    rows.append({'name': name, 'version': version,
                 'notices': copy_notices(package, name + '-' + version, output / 'datatables')})
for name in ['lucide-LICENSE', 'feather-LICENSE']:
    shutil.copyfile(icons / name, output / 'datatables' / name)
(output / 'bundled-libraries.json').write_text(json.dumps(rows, indent=2) + '\n')
print('PASS: actual bundled module license notices collected', flush=True)
